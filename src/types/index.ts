export type AccountingEntryType = 'income' | 'expense' | 'adjustment';
export type AccountingEntryCategory =
  | 'freight_revenue'    // Ingresos por fletes
  | 'fuel'               // Combustible
  | 'tolls'              // Casetas
  | 'viatics'            // Viáticos
  | 'maintenance'        // Mantenimiento
  | 'insurance'          // Seguros
  | 'salaries'           // Nómina / Sueldos
  | 'admin'              // Gastos administrativos
  | 'taxes'              // Impuestos / ISR / IVA
  | 'financing'          // Financiamiento / Leasing
  | 'other_income'       // Otros ingresos
  | 'other_expense';     // Otros egresos

export interface AccountingEntry {
  id: string;
  periodId: string;
  type: AccountingEntryType;
  category: AccountingEntryCategory;
  description: string;
  amount: number;
  date: string;
  reference?: string;   // Número de factura, folio, etc.
  notes?: string;
  /** true = generado automáticamente desde viajes/gastos/mantenimientos */
  isAutoGenerated: boolean;
}

export type PeriodStatus = 'open' | 'closed';

export interface AccountingPeriod {
  id: string;
  year: number;
  month: number;         // 1-12
  status: PeriodStatus;
  closedAt?: string;
  closedBy?: string;
  notes?: string;
  /** Saldo inicial del periodo (arrastrado del mes anterior) */
  openingBalance: number;
}
