import StatusBadge from '../components/ui/StatusBadge';
import EmptyState from '../components/ui/EmptyState';
import PageHeader from '../components/ui/PageHeader';
import { formatCurrency } from '../utils/formatters';
import {
  ResponsiveContainer, AreaChart, Area, XAxis, YAxis,
  CartesianGrid, Tooltip, BarChart, Bar, Legend,
} from 'recharts';

// ─── Constantes ───────────────────────────────────────────────────────────────

const MONTHS = [
  'Enero', 'Febrero', 'Marzo', 'Abril', 'Mayo', 'Junio',
  'Julio', 'Agosto', 'Septiembre', 'Octubre', 'Noviembre', 'Diciembre',
];

const ENTRY_CATEGORIES: { value: AccountingEntryCategory; label: string; type: AccountingEntryType }[] = [
  { value: 'freight_revenue', label: 'Ingresos por fletes',       type: 'income'  },
  { value: 'other_income',    label: 'Otros ingresos',            type: 'income'  },
  { value: 'fuel',            label: 'Combustible',               type: 'expense' },
  { value: 'tolls',           label: 'Casetas / Peajes',          type: 'expense' },
  { value: 'viatics',         label: 'Viáticos de operadores',    type: 'expense' },
  { value: 'maintenance',     label: 'Mantenimiento de flotilla', type: 'expense' },
  { value: 'insurance',       label: 'Seguros',                   type: 'expense' },
  { value: 'salaries',        label: 'Nómina / Sueldos',          type: 'expense' },
  { value: 'admin',           label: 'Gastos administrativos',    type: 'expense' },
  { value: 'taxes',           label: 'Impuestos (ISR / IVA)',     type: 'expense' },
  { value: 'financing',       label: 'Financiamiento / Leasing',  type: 'expense' },
  { value: 'other_expense',   label: 'Otros egresos',             type: 'expense' },
];

const INCOME_CATEGORIES      = ENTRY_CATEGORIES.filter(c => c.type === 'income');
const EXPENSE_CATEGORIES_ACC = ENTRY_CATEGORIES.filter(c => c.type === 'expense');

type AccountingTab = 'summary' | 'income_statement' | 'cashflow' | 'ledger';

const TABS: { id: AccountingTab; label: string; icon: ComponentType<{ className?: string }> }[] = [
  { id: 'summary',          label: 'Resumen',              icon: BarChart3   },
  { id: 'income_statement', label: 'Estado de Resultados', icon: FileText    },
  { id: 'cashflow',         label: 'Flujo de Caja',        icon: TrendingUp  },
  { id: 'ledger',           label: 'Libro Diario',         icon: BookOpen    },
];

const PERIOD_STATUS: Record<string, { label: string; color: string }> = {
  open:   { label: 'Abierto', color: 'bg-emerald-500/20 text-emerald-400 border-emerald-500/30' },
  closed: { label: 'Cerrado', color: 'bg-slate-500/20 text-slate-400 border-slate-500/30' },
};

const EMPTY_ENTRY: Omit<AccountingEntry, 'id'> = {
  periodId: '',
  type: 'income',
  category: 'freight_revenue',
  description: '',
  amount: 0,
  date: new Date().toISOString().split('T')[0],
  reference: '',
  notes: '',
  isAutoGenerated: false,
};

// ─── Helpers ──────────────────────────────────────────────────────────────────

function periodLabel(p: AccountingPeriod) {
  return `${MONTHS[p.month - 1]} ${p.year}`;
}

function calcPeriodTotals(entries: AccountingEntry[], periodId: string) {
  const pe = entries.filter(e => e.periodId === periodId);
  const income     = pe.filter(e => e.type === 'income').reduce((s, e) => s + e.amount, 0);
  const expense    = pe.filter(e => e.type === 'expense').reduce((s, e) => s + e.amount, 0);
  const adjustment = pe.filter(e => e.type === 'adjustment').reduce((s, e) => s + e.amount, 0);
  const net        = income + adjustment - expense;
  return { income, expense, adjustment, net, count: pe.length };
}

// ─── Componente principal ─────────────────────────────────────────────────────

export default function AccountingPage() {
  const { periods, entries, addEntry, updateEntry, deleteEntry, closePeriod, reopenPeriod, addPeriod } =
    useAccountingStore();
  const { currentUser } = useAuthStore();

  const [activeTab, setActiveTab]               = useState<AccountingTab>('summary');
  const [selectedPeriodId, setSelectedPeriodId] = useState<string>(periods[periods.length - 1]?.id ?? '');
  const [entryModalOpen, setEntryModalOpen]     = useState(false);
  const [editingEntryId, setEditingEntryId]     = useState<string | null>(null);
  const [entryForm, setEntryForm]               = useState<Omit<AccountingEntry, 'id'>>(EMPTY_ENTRY);
  const [closeModalOpen, setCloseModalOpen]     = useState(false);
  const [closeNotes, setCloseNotes]             = useState('');
  const [newPeriodModalOpen, setNewPeriodModalOpen] = useState(false);
  const [newPeriodMonth, setNewPeriodMonth]     = useState(new Date().getMonth() + 1);
  const [newPeriodYear, setNewPeriodYear]       = useState(new Date().getFullYear());

  const selectedPeriod = periods.find(p => p.id === selectedPeriodId);
  const periodEntries  = entries.filter(e => e.periodId === selectedPeriodId);
  const periodTotals   = calcPeriodTotals(entries, selectedPeriodId);
  const isOpen         = selectedPeriod?.status === 'open';

  // ─── Datos para gráficas ──────────────────────────────────────────────────

  const chartData = useMemo(() => {
    return [...periods]
      .sort((a, b) => a.year * 100 + a.month - (b.year * 100 + b.month))
      .map(p => {
        const t = calcPeriodTotals(entries, p.id);
        return {
          mes:      `${MONTHS[p.month - 1].slice(0, 3)} ${String(p.year).slice(2)}`,
          Ingresos: t.income,
          Egresos:  t.expense,
          Utilidad: t.net,
        };
      });
  }, [periods, entries]);

  const expenseBreakdown = useMemo(() => {
    return EXPENSE_CATEGORIES_ACC
      .map(cat => ({
        label:  cat.label,
        amount: periodEntries.filter(e => e.category === cat.value).reduce((s, e) => s + e.amount, 0),
      }))
      .filter(c => c.amount > 0)
      .sort((a, b) => b.amount - a.amount);
  }, [periodEntries]);

  const incomeStatementRows = useMemo(() => {
    const incomeByCategory = INCOME_CATEGORIES.map(cat => ({
      label:  cat.label,
      amount: periodEntries.filter(e => e.category === cat.value).reduce((s, e) => s + e.amount, 0),
    })).filter(c => c.amount > 0);

    const expenseByCategory = EXPENSE_CATEGORIES_ACC.map(cat => ({
      label:  cat.label,
      amount: periodEntries.filter(e => e.category === cat.value).reduce((s, e) => s + e.amount, 0),
    })).filter(c => c.amount > 0);

    return { incomeByCategory, expenseByCategory };
  }, [periodEntries]);

  // ─── Handlers ─────────────────────────────────────────────────────────────

  const openAddEntry = () => {
    setEntryForm({ ...EMPTY_ENTRY, periodId: selectedPeriodId, date: new Date().toISOString().split('T')[0] });
    setEditingEntryId(null);
    setEntryModalOpen(true);
  };
  const openEditEntry = (e: AccountingEntry) => {
    const { id, ...rest } = e;
    setEntryForm(rest);
    setEditingEntryId(id);
    setEntryModalOpen(true);
  };
  const handleSaveEntry = () => {
    if (editingEntryId) updateEntry(editingEntryId, entryForm); else addEntry(entryForm);
    setEntryModalOpen(false);
  };
  const fe = (key: keyof Omit<AccountingEntry, 'id'>, val: string | number | boolean) =>
    setEntryForm(p => ({ ...p, [key]: val }));

  const handleClosePeriod = () => {
    if (selectedPeriod) {
      closePeriod(selectedPeriod.id, currentUser.name, closeNotes);
      setCloseModalOpen(false);
      setCloseNotes('');
    }
  };

  const handleAddPeriod = () => {
    const id = `per-${newPeriodYear}-${String(newPeriodMonth).padStart(2, '0')}`;
    if (periods.find(p => p.id === id)) return;
    const lastPeriod   = [...periods].sort((a, b) => b.year * 100 + b.month - (a.year * 100 + a.month))[0];
    const prevTotals   = lastPeriod ? calcPeriodTotals(entries, lastPeriod.id) : { net: 0 };
    const openingBalance = (lastPeriod?.openingBalance ?? 0) + prevTotals.net;
    addPeriod({ year: newPeriodYear, month: newPeriodMonth, status: 'open', openingBalance });
    setSelectedPeriodId(id);
    setNewPeriodModalOpen(false);
  };

  const availableCategories = entryForm.type === 'income'
    ? INCOME_CATEGORIES
    : entryForm.type === 'adjustment'
    ? ENTRY_CATEGORIES
    : EXPENSE_CATEGORIES_ACC;

  // ─── Render ───────────────────────────────────────────────────────────────

  return (
    <div className="space-y-5">
      <PageHeader
        title="Contabilidad Mensual"
        subtitle="Períodos contables, estado de resultados y flujo de caja"
        icon={BookOpen}
      />

      {/* ── Selector de periodo + acciones ───────────────────────────────── */}
      <div className="flex flex-wrap items-center gap-3">
        <div className="flex items-center gap-2">
          <Calendar className="w-4 h-4 text-slate-400" />
          <select
            value={selectedPeriodId}
            onChange={e => setSelectedPeriodId(e.target.value)}
            className="px-3 py-2 bg-slate-700/50 border border-slate-600 rounded-lg text-sm text-white focus:outline-none focus:border-blue-500"
          >
            {[...periods]
              .sort((a, b) => b.year * 100 + b.month - (a.year * 100 + a.month))
              .map(p => (
                <option key={p.id} value={p.id}>
                  {periodLabel(p)} {p.status === 'closed' ? '(Cerrado)' : '(Abierto)'}
                </option>
              ))}
          </select>
        </div>

        {selectedPeriod && (
          <StatusBadge
            colorClass={PERIOD_STATUS[selectedPeriod.status].color}
            label={PERIOD_STATUS[selectedPeriod.status].label}
          />
        )}

        <div className="ml-auto flex gap-2">
          <button
            onClick={() => setNewPeriodModalOpen(true)}
            className="flex items-center gap-2 px-3 py-2 text-sm bg-slate-700 hover:bg-slate-600 text-slate-300 hover:text-white border border-slate-600 rounded-lg transition-colors"
          >
            <Plus className="w-4 h-4" /> Nuevo periodo
          </button>
          {isOpen && (
            <>
              <button
                onClick={openAddEntry}
                className="flex items-center gap-2 px-4 py-2 text-sm bg-blue-600 hover:bg-blue-500 text-white rounded-lg transition-colors font-medium"
              >
                <Plus className="w-4 h-4" /> Agregar entrada
              </button>
              <button
                onClick={() => setCloseModalOpen(true)}
                className="flex items-center gap-2 px-3 py-2 text-sm bg-amber-600/20 hover:bg-amber-600/30 text-amber-400 border border-amber-500/30 rounded-lg transition-colors"
              >
                <Lock className="w-4 h-4" /> Cerrar periodo
              </button>
            </>
          )}
          {!isOpen && selectedPeriod && (
            <button
              onClick={() => reopenPeriod(selectedPeriod.id)}
              className="flex items-center gap-2 px-3 py-2 text-sm bg-slate-700 hover:bg-slate-600 text-slate-300 border border-slate-600 rounded-lg transition-colors"
            >
              <Unlock className="w-4 h-4" /> Reabrir
            </button>
          )}
        </div>
      </div>

      {/* ── KPIs del periodo ─────────────────────────────────────────────── */}
      {selectedPeriod && (
        <div className="grid grid-cols-2 lg:grid-cols-4 gap-4">
          <div className="bg-slate-800 border border-slate-700/50 rounded-xl p-4">
            <div className="flex items-center gap-2 mb-2">
              <ArrowUpRight className="w-4 h-4 text-emerald-400" />
              <p className="text-xs text-slate-400">Ingresos del periodo</p>
            </div>
            <p className="text-xl font-bold text-emerald-400">{formatCurrency(periodTotals.income)}</p>
            {periodTotals.adjustment !== 0 && (
              <p className="text-xs text-slate-500 mt-0.5">+{formatCurrency(periodTotals.adjustment)} ajustes</p>
            )}
          </div>
          <div className="bg-slate-800 border border-slate-700/50 rounded-xl p-4">
            <div className="flex items-center gap-2 mb-2">
              <ArrowDownRight className="w-4 h-4 text-rose-400" />
              <p className="text-xs text-slate-400">Egresos del periodo</p>
            </div>
            <p className="text-xl font-bold text-rose-400">{formatCurrency(periodTotals.expense)}</p>
          </div>
          <div className={`border rounded-xl p-4 ${
            periodTotals.net >= 0 ? 'bg-emerald-500/5 border-emerald-500/20' : 'bg-rose-500/5 border-rose-500/20'
          }`}>
            <div className="flex items-center gap-2 mb-2">
              <TrendingUp className={`w-4 h-4 ${periodTotals.net >= 0 ? 'text-emerald-400' : 'text-rose-400'}`} />
              <p className="text-xs text-slate-400">Utilidad neta</p>
            </div>
            <p className={`text-xl font-bold ${periodTotals.net >= 0 ? 'text-emerald-400' : 'text-rose-400'}`}>
              {formatCurrency(periodTotals.net)}
            </p>
            {(periodTotals.income + periodTotals.adjustment) > 0 && (
              <p className="text-xs text-slate-500 mt-0.5">
                {((periodTotals.net / (periodTotals.income + periodTotals.adjustment)) * 100).toFixed(1)}% margen
              </p>
            )}
          </div>
          <div className="bg-slate-800 border border-slate-700/50 rounded-xl p-4">
            <div className="flex items-center gap-2 mb-2">
              <DollarSign className="w-4 h-4 text-blue-400" />
              <p className="text-xs text-slate-400">Saldo al cierre</p>
            </div>
            <p className="text-xl font-bold text-blue-400">
              {formatCurrency(selectedPeriod.openingBalance + periodTotals.net)}
            </p>
            <p className="text-xs text-slate-500 mt-0.5">Saldo inicial: {formatCurrency(selectedPeriod.openingBalance)}</p>
          </div>
        </div>
      )}

      {/* ── Sub-tabs ─────────────────────────────────────────────────────── */}
      <div className="flex gap-1 p-1 bg-slate-800 border border-slate-700/50 rounded-xl w-fit flex-wrap">
        {TABS.map(t => (
          <button
            key={t.id}
            onClick={() => setActiveTab(t.id)}
            className={`flex items-center gap-2 px-4 py-2 rounded-lg text-sm font-medium transition-colors ${
              activeTab === t.id ? 'bg-blue-600 text-white' : 'text-slate-400 hover:text-white'
            }`}
          >
            <t.icon className="w-4 h-4" />
            {t.label}
          </button>
        ))}
      </div>

      {/* ══ TAB: RESUMEN ═══════════════════════════════════════════════════ */}
      {activeTab === 'summary' && (
        <div className="space-y-4">
          <div className="bg-slate-800 border border-slate-700/50 rounded-xl p-5">
            <h2 className="text-sm font-semibold text-slate-300 mb-4">Evolución histórica — todos los periodos</h2>
            <ResponsiveContainer width="100%" height={240}>
              <AreaChart data={chartData}>
                <defs>
                  <linearGradient id="gradIng" x1="0" y1="0" x2="0" y2="1">
                    <stop offset="5%"  stopColor="#10b981" stopOpacity={0.3} />
                    <stop offset="95%" stopColor="#10b981" stopOpacity={0} />
                  </linearGradient>
                  <linearGradient id="gradEgr" x1="0" y1="0" x2="0" y2="1">
                    <stop offset="5%"  stopColor="#f43f5e" stopOpacity={0.3} />
                    <stop offset="95%" stopColor="#f43f5e" stopOpacity={0} />
                  </linearGradient>
                </defs>
                <CartesianGrid strokeDasharray="3 3" stroke="#334155" />
                <XAxis dataKey="mes" tick={{ fill: '#94a3b8', fontSize: 11 }} axisLine={false} tickLine={false} />
                <YAxis tick={{ fill: '#94a3b8', fontSize: 11 }} axisLine={false} tickLine={false}
                  tickFormatter={v => `$${(v / 1000).toFixed(0)}k`} />
                <Tooltip
                  contentStyle={{ background: '#1e293b', border: '1px solid #334155', borderRadius: 8 }}
                  formatter={(v: number) => [formatCurrency(v), '']}
                />
                <Legend wrapperStyle={{ fontSize: 12, color: '#94a3b8' }} />
                <Area type="monotone" dataKey="Ingresos" stroke="#10b981" fill="url(#gradIng)" strokeWidth={2} />
                <Area type="monotone" dataKey="Egresos"  stroke="#f43f5e" fill="url(#gradEgr)" strokeWidth={2} />
              </AreaChart>
            </ResponsiveContainer>
          </div>

          <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
            <div className="bg-slate-800 border border-slate-700/50 rounded-xl p-5">
              <h2 className="text-sm font-semibold text-slate-300 mb-4">Utilidad neta por periodo</h2>
              <ResponsiveContainer width="100%" height={200}>
                <BarChart data={chartData}>
                  <CartesianGrid strokeDasharray="3 3" stroke="#334155" />
                  <XAxis dataKey="mes" tick={{ fill: '#94a3b8', fontSize: 11 }} axisLine={false} tickLine={false} />
                  <YAxis tick={{ fill: '#94a3b8', fontSize: 11 }} axisLine={false} tickLine={false}
                    tickFormatter={v => `$${(v / 1000).toFixed(0)}k`} />
                  <Tooltip
                    contentStyle={{ background: '#1e293b', border: '1px solid #334155', borderRadius: 8 }}
                    formatter={(v: number) => [formatCurrency(v), '']}
                  />
                  <Bar dataKey="Utilidad" fill="#3b82f6" radius={[4, 4, 0, 0]} />
                </BarChart>
              </ResponsiveContainer>
            </div>

            <div className="bg-slate-800 border border-slate-700/50 rounded-xl p-5">
              <h2 className="text-sm font-semibold text-slate-300 mb-4">
                Egresos por categoría — {selectedPeriod ? periodLabel(selectedPeriod) : ''}
              </h2>
              {expenseBreakdown.length === 0 ? (
                <p className="text-sm text-slate-500 text-center py-8">Sin egresos registrados</p>
              ) : (
                <div className="space-y-2">
                  {expenseBreakdown.map(cat => {
                    const pct = periodTotals.expense > 0 ? (cat.amount / periodTotals.expense) * 100 : 0;
                    return (
                      <div key={cat.label} className="space-y-0.5">
                        <div className="flex justify-between text-xs">
                          <span className="text-slate-400">{cat.label}</span>
                          <div className="flex items-center gap-2">
                            <span className="text-slate-500">{pct.toFixed(1)}%</span>
                            <span className="text-rose-400 font-medium">{formatCurrency(cat.amount)}</span>
                          </div>
                        </div>
                        <div className="w-full bg-slate-700 rounded-full h-1">
                          <div className="bg-rose-500/70 h-1 rounded-full" style={{ width: `${pct}%` }} />
                        </div>
                      </div>
                    );
                  })}
                </div>
              )}
            </div>
          </div>

          <div className="bg-slate-800 border border-slate-700/50 rounded-xl overflow-hidden">
            <div className="px-5 py-4 border-b border-slate-700">
              <h2 className="text-sm font-semibold text-slate-300">Resumen de todos los periodos</h2>
            </div>
            <div className="overflow-x-auto">
              <table className="w-full text-sm">
                <thead>
                  <tr className="border-b border-slate-700">
                    {['Periodo', 'Estatus', 'Saldo inicial', 'Ingresos', 'Egresos', 'Utilidad', 'Saldo final', 'Cierre'].map(h => (
                      <th key={h} className="px-4 py-3 text-left text-xs font-medium text-slate-400 uppercase tracking-wide whitespace-nowrap">{h}</th>
                    ))}
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-700/50">
                  {[...periods]
                    .sort((a, b) => b.year * 100 + b.month - (a.year * 100 + a.month))
                    .map(p => {
                      const t   = calcPeriodTotals(entries, p.id);
                      const closing = p.openingBalance + t.net;
                      const st  = PERIOD_STATUS[p.status];
                      return (
                        <tr
                          key={p.id}
                          onClick={() => setSelectedPeriodId(p.id)}
                          className={`hover:bg-slate-700/20 cursor-pointer transition-colors ${
                            p.id === selectedPeriodId ? 'bg-blue-600/10' : ''
                          }`}
                        >
                          <td className="px-4 py-3 font-semibold text-white whitespace-nowrap">{periodLabel(p)}</td>
                          <td className="px-4 py-3"><StatusBadge colorClass={st.color} label={st.label} /></td>
                          <td className="px-4 py-3 text-slate-400">{formatCurrency(p.openingBalance)}</td>
                          <td className="px-4 py-3 text-emerald-400 font-medium">{formatCurrency(t.income + t.adjustment)}</td>
                          <td className="px-4 py-3 text-rose-400">{formatCurrency(t.expense)}</td>
                          <td className={`px-4 py-3 font-bold ${t.net >= 0 ? 'text-emerald-400' : 'text-rose-400'}`}>
                            {formatCurrency(t.net)}
                          </td>
                          <td className="px-4 py-3 text-blue-400 font-medium">{formatCurrency(closing)}</td>
                          <td className="px-4 py-3 text-xs text-slate-500">{p.closedAt ?? '—'}</td>
                        </tr>
                      );
                    })}
                </tbody>
              </table>
            </div>
          </div>
        </div>
      )}

      {/* ══ TAB: ESTADO DE RESULTADOS ══════════════════════════════════════ */}
      {activeTab === 'income_statement' && (
        <div className="bg-slate-800 border border-slate-700/50 rounded-xl overflow-hidden">
          <div className="px-6 py-4 border-b border-slate-700 flex items-center justify-between">
            <h2 className="text-sm font-semibold text-slate-300">
              Estado de Resultados — {selectedPeriod ? periodLabel(selectedPeriod) : ''}
            </h2>
            <span className="text-xs text-slate-500">Periodo {selectedPeriod?.status === 'closed' ? 'cerrado' : 'en curso'}</span>
          </div>
          <div className="p-6 space-y-6">
            <div>
              <div className="flex items-center gap-2 mb-3">
                <ArrowUpRight className="w-4 h-4 text-emerald-400" />
                <h3 className="text-sm font-semibold text-emerald-400 uppercase tracking-wide">Ingresos</h3>
              </div>
              <div className="space-y-1.5">
                {incomeStatementRows.incomeByCategory.map(row => (
                  <div key={row.label} className="flex justify-between py-1.5 px-3 rounded-lg hover:bg-slate-700/30">
                    <span className="text-sm text-slate-300">{row.label}</span>
                    <span className="text-sm font-medium text-emerald-400">{formatCurrency(row.amount)}</span>
                  </div>
                ))}
                {periodTotals.adjustment > 0 && (
                  <div className="flex justify-between py-1.5 px-3 rounded-lg hover:bg-slate-700/30">
                    <span className="text-sm text-slate-300">Ajustes (créditos)</span>
                    <span className="text-sm font-medium text-amber-400">{formatCurrency(periodTotals.adjustment)}</span>
                  </div>
                )}
                <div className="flex justify-between py-2 px-3 bg-emerald-500/10 border border-emerald-500/20 rounded-lg mt-2">
                  <span className="text-sm font-bold text-white">Total Ingresos</span>
                  <span className="text-sm font-bold text-emerald-400">{formatCurrency(periodTotals.income + periodTotals.adjustment)}</span>
                </div>
              </div>
            </div>

            <div className="border-t border-slate-700" />

            <div>
              <div className="flex items-center gap-2 mb-3">
                <ArrowDownRight className="w-4 h-4 text-rose-400" />
                <h3 className="text-sm font-semibold text-rose-400 uppercase tracking-wide">Egresos</h3>
              </div>
              <div className="space-y-1.5">
                {incomeStatementRows.expenseByCategory.map(row => (
                  <div key={row.label} className="flex justify-between py-1.5 px-3 rounded-lg hover:bg-slate-700/30">
                    <span className="text-sm text-slate-300">{row.label}</span>
                    <span className="text-sm font-medium text-rose-400">{formatCurrency(row.amount)}</span>
                  </div>
                ))}
                <div className="flex justify-between py-2 px-3 bg-rose-500/10 border border-rose-500/20 rounded-lg mt-2">
                  <span className="text-sm font-bold text-white">Total Egresos</span>
                  <span className="text-sm font-bold text-rose-400">{formatCurrency(periodTotals.expense)}</span>
                </div>
              </div>
            </div>

            <div className="border-t border-slate-700" />

            <div className={`flex justify-between items-center p-4 rounded-xl border ${
              periodTotals.net >= 0 ? 'bg-emerald-500/10 border-emerald-500/30' : 'bg-rose-500/10 border-rose-500/30'
            }`}>
              <div>
                <p className="text-xs text-slate-400 uppercase tracking-wide mb-0.5">Utilidad / Pérdida neta del periodo</p>
                <p className={`text-2xl font-bold ${periodTotals.net >= 0 ? 'text-emerald-400' : 'text-rose-400'}`}>
                  {formatCurrency(periodTotals.net)}
                </p>
              </div>
              {periodTotals.income > 0 && (
                <div className="text-right">
                  <p className="text-xs text-slate-400">Margen</p>
                  <p className={`text-xl font-bold ${periodTotals.net >= 0 ? 'text-emerald-400' : 'text-rose-400'}`}>
                    {((periodTotals.net / (periodTotals.income + periodTotals.adjustment)) * 100).toFixed(1)}%
                  </p>
                </div>
              )}
            </div>
          </div>
        </div>
      )}

      {/* ══ TAB: FLUJO DE CAJA ═════════════════════════════════════════════ */}
      {activeTab === 'cashflow' && (
        <div className="space-y-4">
          <div className="bg-slate-800 border border-slate-700/50 rounded-xl p-5">
            <h2 className="text-sm font-semibold text-slate-300 mb-4">Flujo de caja — Ingresos vs Egresos por periodo</h2>
            <ResponsiveContainer width="100%" height={260}>
              <BarChart data={chartData} barGap={4}>
                <CartesianGrid strokeDasharray="3 3" stroke="#334155" />
                <XAxis dataKey="mes" tick={{ fill: '#94a3b8', fontSize: 11 }} axisLine={false} tickLine={false} />
                <YAxis tick={{ fill: '#94a3b8', fontSize: 11 }} axisLine={false} tickLine={false}
                  tickFormatter={v => `$${(v / 1000).toFixed(0)}k`} />
                <Tooltip
                  contentStyle={{ background: '#1e293b', border: '1px solid #334155', borderRadius: 8 }}
                  formatter={(v: number) => [formatCurrency(v), '']}
                />
                <Legend wrapperStyle={{ fontSize: 12, color: '#94a3b8' }} />
                <Bar dataKey="Ingresos" fill="#10b981" radius={[4, 4, 0, 0]} />
                <Bar dataKey="Egresos"  fill="#f43f5e" radius={[4, 4, 0, 0]} />
                <Bar dataKey="Utilidad" fill="#3b82f6" radius={[4, 4, 0, 0]} />
              </BarChart>
            </ResponsiveContainer>
          </div>

          <div className="bg-slate-800 border border-slate-700/50 rounded-xl overflow-hidden">
            <div className="px-5 py-4 border-b border-slate-700">
              <h2 className="text-sm font-semibold text-slate-300">Evolución del saldo</h2>
            </div>
            <div className="overflow-x-auto">
              <table className="w-full text-sm">
                <thead>
                  <tr className="border-b border-slate-700">
                    {['Periodo', 'Saldo inicial', 'Entradas', 'Salidas', 'Flujo neto', 'Saldo final'].map(h => (
                      <th key={h} className="px-4 py-3 text-left text-xs font-medium text-slate-400 uppercase tracking-wide">{h}</th>
                    ))}
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-700/50">
                  {[...periods]
                    .sort((a, b) => a.year * 100 + a.month - (b.year * 100 + b.month))
                    .map(p => {
                      const t = calcPeriodTotals(entries, p.id);
                      const closing = p.openingBalance + t.net;
                      return (
                        <tr key={p.id} className="hover:bg-slate-700/20">
                          <td className="px-4 py-3 font-medium text-white">{periodLabel(p)}</td>
                          <td className="px-4 py-3 text-slate-400">{formatCurrency(p.openingBalance)}</td>
                          <td className="px-4 py-3 text-emerald-400">{formatCurrency(t.income + t.adjustment)}</td>
                          <td className="px-4 py-3 text-rose-400">{formatCurrency(t.expense)}</td>
                          <td className={`px-4 py-3 font-bold ${t.net >= 0 ? 'text-emerald-400' : 'text-rose-400'}`}>
                            {t.net >= 0 ? '+' : ''}{formatCurrency(t.net)}
                          </td>
                          <td className="px-4 py-3 text-blue-400 font-bold">{formatCurrency(closing)}</td>
                        </tr>
                      );
                    })}
                </tbody>
              </table>
            </div>
          </div>
        </div>
      )}

      {/* ══ TAB: LIBRO DIARIO ══════════════════════════════════════════════ */}
      {activeTab === 'ledger' && (
        <div className="space-y-4">
          <p className="text-sm text-slate-400">
            {periodEntries.length} entradas en {selectedPeriod ? periodLabel(selectedPeriod) : 'este periodo'}
            {!isOpen && <span className="ml-2 text-amber-400 text-xs">(periodo cerrado — solo lectura)</span>}
          </p>

          {periodEntries.length === 0 ? (
            <EmptyState
              icon={BookOpen}
              title="Sin entradas"
              description="Agrega la primera entrada contable para este periodo."
              action={isOpen ? { label: 'Agregar entrada', onClick: openAddEntry } : undefined}
            />
          ) : (
            <div className="bg-slate-800 border border-slate-700/50 rounded-xl overflow-hidden">
              <div className="overflow-x-auto">
                <table className="w-full text-sm">
                  <thead>
                    <tr className="border-b border-slate-700">
                      {['Fecha', 'Tipo', 'Categoría', 'Descripción', 'Referencia', 'Monto', ''].map(h => (
                        <th key={h} className="px-4 py-3 text-left text-xs font-medium text-slate-400 uppercase tracking-wide whitespace-nowrap">{h}</th>
                      ))}
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-700/50">
                    {[...periodEntries]
                      .sort((a, b) => b.date.localeCompare(a.date))
                      .map(entry => {
                        const catLabel = ENTRY_CATEGORIES.find(c => c.value === entry.category)?.label ?? entry.category;
                        const isIncome = entry.type === 'income';
                        const isAdj    = entry.type === 'adjustment';
                        return (
                          <tr key={entry.id} className="hover:bg-slate-700/20 transition-colors">
                            <td className="px-4 py-3 text-slate-400 whitespace-nowrap">{entry.date}</td>
                            <td className="px-4 py-3">
                              <span className={`inline-flex items-center gap-1 text-xs px-2 py-0.5 rounded-full border ${
                                isIncome ? 'bg-emerald-500/20 text-emerald-400 border-emerald-500/30'
                                : isAdj  ? 'bg-amber-500/20 text-amber-400 border-amber-500/30'
                                         : 'bg-rose-500/20 text-rose-400 border-rose-500/30'
                              }`}>
                                {isIncome ? <ArrowUpRight className="w-3 h-3" /> : isAdj ? <Minus className="w-3 h-3" /> : <ArrowDownRight className="w-3 h-3" />}
                                {isIncome ? 'Ingreso' : isAdj ? 'Ajuste' : 'Egreso'}
                              </span>
                            </td>
                            <td className="px-4 py-3 text-slate-300 whitespace-nowrap">{catLabel}</td>
                            <td className="px-4 py-3 text-slate-300 max-w-xs">
                              <p className="truncate">{entry.description}</p>
                              {entry.notes && <p className="text-xs text-slate-500 italic truncate">{entry.notes}</p>}
                            </td>
                            <td className="px-4 py-3 text-slate-500 text-xs">{entry.reference ?? '—'}</td>
                            <td className="px-4 py-3">
                              <span className={`font-bold ${
                                isIncome || isAdj ? 'text-emerald-400' : 'text-rose-400'
                              }`}>
                                {isIncome || isAdj ? '+' : '-'}{formatCurrency(entry.amount)}
                              </span>
                            </td>
                            <td className="px-4 py-3">
                              {isOpen && !entry.isAutoGenerated && (
                                <div className="flex items-center gap-1">
                                  <button onClick={() => openEditEntry(entry)} className="p-1.5 text-slate-400 hover:text-blue-400 hover:bg-blue-500/10 rounded-lg transition-colors">
                                    <Pencil className="w-3.5 h-3.5" />
                                  </button>
                                  <button onClick={() => deleteEntry(entry.id)} className="p-1.5 text-slate-400 hover:text-rose-400 hover:bg-rose-500/10 rounded-lg transition-colors">
                                    <Trash2 className="w-3.5 h-3.5" />
                                  </button>
                                </div>
                              )}
                              {entry.isAutoGenerated && (
                                <span className="text-xs text-slate-600 italic">auto</span>
                              )}
                            </td>
                          </tr>
                        );
                      })}
                  </tbody>
                </table>
              </div>
            </div>
          )}
        </div>
      )}

      {/* ══ MODAL: NUEVA / EDITAR ENTRADA ══════════════════════════════════ */}
      <Modal
        isOpen={entryModalOpen}
        onClose={() => setEntryModalOpen(false)}
        title={editingEntryId ? 'Editar Entrada' : 'Nueva Entrada Contable'}
        size="lg"
      >
        <div className="grid grid-cols-2 gap-4">
          <FormField label="Tipo" required>
            <Select
              value={entryForm.type}
              onChange={e => {
                const t = e.target.value as AccountingEntryType;
                const defaultCat: AccountingEntryCategory =
                  t === 'income' ? 'freight_revenue' : t === 'adjustment' ? 'other_income' : 'fuel';
                fe('type', t);
                fe('category', defaultCat);
              }}
            >
              <option value="income">Ingreso</option>
              <option value="expense">Egreso</option>
              <option value="adjustment">Ajuste</option>
            </Select>
          </FormField>

          <FormField label="Categoría" required>
            <Select
              value={entryForm.category}
              onChange={e => fe('category', e.target.value as AccountingEntryCategory)}
            >
              {availableCategories.map(c => (
                <option key={c.value} value={c.value}>{c.label}</option>
              ))}
            </Select>
          </FormField>

          <FormField label="Descripción" required className="col-span-2">
            <Input
              value={entryForm.description}
              onChange={e => fe('description', e.target.value)}
              placeholder="Descripción de la entrada contable"
            />
          </FormField>

          <FormField label="Monto (MXN)" required>
            <Input
              type="number"
              value={entryForm.amount}
              onChange={e => fe('amount', +e.target.value)}
              min={0}
            />
          </FormField>

          <FormField label="Fecha" required>
            <Input
              type="date"
              value={entryForm.date}
              onChange={e => fe('date', e.target.value)}
            />
          </FormField>

          <FormField label="Referencia (folio, factura)">
            <Input
              value={entryForm.reference ?? ''}
              onChange={e => fe('reference', e.target.value)}
              placeholder="FAC-001, ISR-0324..."
            />
          </FormField>

          <FormField label="Notas">
            <Input
              value={entryForm.notes ?? ''}
              onChange={e => fe('notes', e.target.value)}
              placeholder="Observaciones adicionales"
            />
          </FormField>
        </div>

        <div className="flex justify-end gap-3 mt-5 pt-4 border-t border-slate-700">
          <button
            onClick={() => setEntryModalOpen(false)}
            className="px-4 py-2 text-sm text-slate-300 hover:text-white bg-slate-700 hover:bg-slate-600 rounded-lg transition-colors"
          >
            Cancelar
          </button>
          <button
            onClick={handleSaveEntry}
            className="px-4 py-2 text-sm text-white bg-blue-600 hover:bg-blue-500 rounded-lg transition-colors font-medium"
          >
            {editingEntryId ? 'Guardar cambios' : 'Agregar entrada'}
          </button>
        </div>
      </Modal>

      {/* ══ MODAL: CERRAR PERIODO ═══════════════════════════════════════════ */}
      <Modal
        isOpen={closeModalOpen}
        onClose={() => setCloseModalOpen(false)}
        title="Cerrar Periodo Contable"
        size="md"
      >
        <div className="space-y-4">
          <div className="flex items-start gap-3 p-4 bg-amber-500/5 border border-amber-500/20 rounded-xl">
            <AlertCircle className="w-5 h-5 text-amber-400 shrink-0 mt-0.5" />
            <div>
              <p className="text-sm font-medium text-white">¿Cerrar {selectedPeriod ? periodLabel(selectedPeriod) : ''}?</p>
              <p className="text-xs text-slate-400 mt-1">
                Las entradas auto-generadas quedarán bloqueadas. Podrás reabrirlo si necesitas hacer correcciones.
              </p>
            </div>
          </div>

          <div className="grid grid-cols-3 gap-3">
            <div className="bg-slate-700/40 rounded-lg p-3 text-center">
              <p className="text-xs text-slate-400 mb-1">Ingresos</p>
              <p className="text-sm font-bold text-emerald-400">{formatCurrency(periodTotals.income + periodTotals.adjustment)}</p>
            </div>
            <div className="bg-slate-700/40 rounded-lg p-3 text-center">
              <p className="text-xs text-slate-400 mb-1">Egresos</p>
              <p className="text-sm font-bold text-rose-400">{formatCurrency(periodTotals.expense)}</p>
            </div>
            <div className={`rounded-lg p-3 text-center ${
              periodTotals.net >= 0 ? 'bg-emerald-500/10' : 'bg-rose-500/10'
            }`}>
              <p className="text-xs text-slate-400 mb-1">Utilidad</p>
              <p className={`text-sm font-bold ${periodTotals.net >= 0 ? 'text-emerald-400' : 'text-rose-400'}`}>
                {formatCurrency(periodTotals.net)}
              </p>
            </div>
          </div>

          <FormField label="Notas de cierre (opcional)">
            <Input
              value={closeNotes}
              onChange={e => setCloseNotes(e.target.value)}
              placeholder="Observaciones del cierre..."
            />
          </FormField>
        </div>

        <div className="flex justify-end gap-3 mt-5 pt-4 border-t border-slate-700">
          <button
            onClick={() => setCloseModalOpen(false)}
            className="px-4 py-2 text-sm text-slate-300 hover:text-white bg-slate-700 hover:bg-slate-600 rounded-lg transition-colors"
          >
            Cancelar
          </button>
          <button
            onClick={handleClosePeriod}
            className="flex items-center gap-2 px-4 py-2 text-sm text-white bg-amber-600 hover:bg-amber-500 rounded-lg transition-colors font-medium"
          >
            <Lock className="w-4 h-4" /> Confirmar cierre
          </button>
        </div>
      </Modal>

      {/* ══ MODAL: NUEVO PERIODO ════════════════════════════════════════════ */}
      <Modal
        isOpen={newPeriodModalOpen}
        onClose={() => setNewPeriodModalOpen(false)}
        title="Abrir Nuevo Periodo Contable"
        size="sm"
      >
        <div className="grid grid-cols-2 gap-4">
          <FormField label="Mes" required>
            <Select value={newPeriodMonth} onChange={e => setNewPeriodMonth(+e.target.value)}>
              {MONTHS.map((m, i) => <option key={i} value={i + 1}>{m}</option>)}
            </Select>
          </FormField>
          <FormField label="Año" required>
            <Input
              type="number"
              value={newPeriodYear}
              onChange={e => setNewPeriodYear(+e.target.value)}
              min={2020}
              max={2099}
            />
          </FormField>
        </div>
        <div className="flex justify-end gap-3 mt-5 pt-4 border-t border-slate-700">
          <button
            onClick={() => setNewPeriodModalOpen(false)}
            className="px-4 py-2 text-sm text-slate-300 hover:text-white bg-slate-700 hover:bg-slate-600 rounded-lg transition-colors"
          >
            Cancelar
          </button>
          <button
            onClick={handleAddPeriod}
            className="flex items-center gap-2 px-4 py-2 text-sm text-white bg-blue-600 hover:bg-blue-500 rounded-lg transition-colors font-medium"
          >
            <Plus className="w-4 h-4" /> Abrir periodo
          </button>
        </div>
      </Modal>
    </div>
  );
}
